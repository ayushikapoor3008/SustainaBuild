def get_climate_data(city_name: str) -> Dict[str, Any]:
    if city_name in CLIMATE_DATABASE:
        return CLIMATE_DATABASE[city_name]
    # Check if city name is a substring
    for key, val in CLIMATE_DATABASE.items():
        if key.lower() in city_name.lower() or city_name.lower() in key.lower():
            return val
    # Fallback to Delhi with notice
    return CLIMATE_DATABASE["Delhi"]
